"""
net.py -- AlexNet-C10: an AlexNet-style CNN (5 conv + 3 FC, ReLU, max-pool)
sized for CIFAR-10 *and* for a fully on-chip RTL accelerator on the XC7Z020.

    input  3 x 32 x 32  uint8 pixels / 255  (no mean/std: BN after conv1 absorbs it,
                                             and zero padding stays exactly 0)
    conv1  3 -> C1  3x3 p1  BN ReLU  maxpool 2x2  -> 16x16
    conv2  C1-> C2  3x3 p1  BN ReLU  maxpool 2x2  ->  8x8
    conv3  C2-> C3  3x3 p1  BN ReLU
    conv4  C3-> C4  3x3 p1  BN ReLU
    conv5  C4-> C5  3x3 p1  BN ReLU  maxpool 2x2  ->  4x4
    fc6    C5*16 -> F6  BN ReLU  (dropout in training)
    fc7    F6 -> F7     BN ReLU  (dropout in training)
    fc8    F7 -> 10

All BN layers are folded into the preceding conv/FC for inference.
The QAT model (QNet) reproduces the integer contract of the RTL:
  weights int8 per-output-channel symmetric in [-127, 127]
  activations uint8 per-tensor (post-ReLU), input scale = 1/255
  fc8 = raw int32 accumulator -> argmax in hardware
"""
import torch
import torch.nn as nn
import torch.nn.functional as F

# channel configuration (must match rtl/cnn_cfg.vh, generated by export_rtl.py)
CFG = dict(C1=32, C2=64, C3=96, C4=96, C5=64, F6=128, F7=128, NCLS=10)
CONV_NAMES = ["conv1", "conv2", "conv3", "conv4", "conv5"]
FC_NAMES = ["fc6", "fc7", "fc8"]
POOL_AFTER = {"conv1": True, "conv2": True, "conv3": False, "conv4": False, "conv5": True}


class AlexNetC10(nn.Module):
    def __init__(self, cfg=CFG, p_drop=0.3):
        super().__init__()
        c = cfg
        chans = [3, c["C1"], c["C2"], c["C3"], c["C4"], c["C5"]]
        self.convs = nn.ModuleList([nn.Conv2d(chans[i], chans[i + 1], 3, padding=1, bias=False) for i in range(5)])
        self.cbns = nn.ModuleList([nn.BatchNorm2d(chans[i + 1]) for i in range(5)])
        self.fc6 = nn.Linear(c["C5"] * 16, c["F6"], bias=False)
        self.bn6 = nn.BatchNorm1d(c["F6"])
        self.fc7 = nn.Linear(c["F6"], c["F7"], bias=False)
        self.bn7 = nn.BatchNorm1d(c["F7"])
        self.fc8 = nn.Linear(c["F7"], c["NCLS"])
        self.drop = nn.Dropout(p_drop)

    def forward(self, x):
        for i, name in enumerate(CONV_NAMES):
            x = F.relu(self.cbns[i](self.convs[i](x)))
            if POOL_AFTER[name]:
                x = F.max_pool2d(x, 2)
        x = torch.flatten(x, 1)
        x = self.drop(F.relu(self.bn6(self.fc6(x))))
        x = self.drop(F.relu(self.bn7(self.fc7(x))))
        return self.fc8(x)


def fold_bn(w, bn):
    """Fold BatchNorm (eval statistics) into weight w (out-channel first).
    Returns (w', b')."""
    s = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    shape = (-1,) + (1,) * (w.dim() - 1)
    return w * s.reshape(shape), bn.bias - bn.running_mean * s


def folded_params(model):
    """List of (name, weight, bias) float tensors with BN folded, in layer order."""
    out = []
    for i, name in enumerate(CONV_NAMES):
        w, b = fold_bn(model.convs[i].weight, model.cbns[i])
        out.append((name, w.detach().clone(), b.detach().clone()))
    w, b = fold_bn(model.fc6.weight, model.bn6)
    out.append(("fc6", w.detach().clone(), b.detach().clone()))
    w, b = fold_bn(model.fc7.weight, model.bn7)
    out.append(("fc7", w.detach().clone(), b.detach().clone()))
    out.append(("fc8", model.fc8.weight.detach().clone(), model.fc8.bias.detach().clone()))
    return out


# ------------------------------------------------------------------------------
# Quantisation-aware model (BN already folded)
# ------------------------------------------------------------------------------
class _RoundSTE(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x):
        return torch.round(x)

    @staticmethod
    def backward(ctx, g):
        return g


def fq_weight(w, per_channel=True):
    """symmetric int8 in [-127, 127] (fake quant).  Per output channel, or one
    scale for the whole tensor (used for fc8 so that argmax over the raw int32
    accumulators equals argmax over the real-valued logits)."""
    if per_channel:
        wmax = w.detach().abs().reshape(w.shape[0], -1).amax(1).clamp_min(1e-8)
    else:
        wmax = w.detach().abs().max().clamp_min(1e-8).repeat(w.shape[0])
    s = (wmax / 127.0).reshape((-1,) + (1,) * (w.dim() - 1))
    return torch.clamp(_RoundSTE.apply(w / s), -127, 127) * s


class ActQuant(nn.Module):
    """uint8 post-ReLU activation fake-quant.  Scale tracks an EMA of the
    batch 99.99th percentile during calibration, then is frozen."""

    def __init__(self, momentum=0.05, pct=0.9999):
        super().__init__()
        self.register_buffer("amax", torch.tensor(0.0))
        self.momentum, self.pct = momentum, pct
        self.calibrating = True

    def scale(self):
        return self.amax.clamp_min(1e-8) / 255.0

    def forward(self, x):
        if self.calibrating and self.training:
            v = torch.quantile(x.detach().flatten()[::7].float(), self.pct)
            self.amax.copy_(v if self.amax == 0 else (1 - self.momentum) * self.amax + self.momentum * v)
        s = self.scale()
        return torch.clamp(_RoundSTE.apply(x / s), 0, 255) * s


class QNet(nn.Module):
    def __init__(self, folded, p_drop=0.1):
        super().__init__()
        self.names = [n for n, _, _ in folded]
        self.w = nn.ParameterList([nn.Parameter(w.clone()) for _, w, _ in folded])
        self.b = nn.ParameterList([nn.Parameter(b.clone()) for _, _, b in folded])
        self.aq = nn.ModuleList([ActQuant() for _ in range(7)])  # after conv1..5, fc6, fc7
        self.drop = nn.Dropout(p_drop)

    def forward(self, x):
        # x: float in [0,1] already on the 1/255 grid
        for i, name in enumerate(CONV_NAMES):
            x = F.conv2d(x, fq_weight(self.w[i]), self.b[i], padding=1)
            x = self.aq[i](F.relu(x))
            if POOL_AFTER[name]:
                x = F.max_pool2d(x, 2)
        x = torch.flatten(x, 1)
        x = self.drop(self.aq[5](F.relu(F.linear(x, fq_weight(self.w[5]), self.b[5]))))
        x = self.drop(self.aq[6](F.relu(F.linear(x, fq_weight(self.w[6]), self.b[6]))))
        return F.linear(x, fq_weight(self.w[7], per_channel=False), self.b[7])

    def act_scales(self):
        return [float(a.scale()) for a in self.aq]
