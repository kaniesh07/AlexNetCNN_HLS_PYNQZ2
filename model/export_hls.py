#!/usr/bin/env python3
"""
export_hls.py -- trained AlexNet-C10 (QAT) -> Vitis HLS weight header + golden
vectors + board files.  Re-uses the integer contract of model/qmodel.py.

  python model/export_hls.py                         # uses model/trained/qat.pt
  python model/export_hls.py --qat build/qat.pt      # after re-training

Writes
  hls/include/cifar_weights.h   all weights/biases/requant params as on-chip ROMs
                                + the layer table (LCFG)
  hls/testbench/data/           golden vectors for the C testbench (N images)
  build/deploy/                 cifar10_test.npz (+expected logits), model_info.json,
                                int_params.npz  (for pynq/evaluate.py)
Prints the exact integer top-1 accuracy on all 10,000 test images: the HLS
kernel computes bit-identical results.

Hardware view of the network (one engine, 8 calls):
  conv1..conv5 : 3x3, pad 1 (2x2 max-pool fused after conv1, conv2, conv5)
  fc6          : exact 4x4 'valid' convolution on the 64x4x4 pool5 map
                 (W_fc6[o, c*16+ky*4+kx] = w[o, c, ky, kx]) -> no flatten logic
  fc7, fc8     : 1x1 convolutions on a 1x1 map; fc8 returns raw int32
"""
import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import qmodel as qm  # noqa: E402

PI, PO = 8, 32
ACC_CLAMP = (1 << 24) - 1          # hardware clamps (acc+bias) to [0, 2^24-1] before requant
CLASSES = ["airplane", "automobile", "bird", "cat", "deer", "dog", "frog", "horse", "ship", "truck"]


def hls_layers(cfg):
    C = [3, cfg["C1"], cfg["C2"], cfg["C3"], cfg["C4"], cfg["C5"]]
    spec = [  # name, cin, cout, H(in), K, pad, pool, raw
        ("conv1", C[0], C[1], 32, 3, 1, 1, 0),
        ("conv2", C[1], C[2], 16, 3, 1, 1, 0),
        ("conv3", C[2], C[3], 8, 3, 1, 0, 0),
        ("conv4", C[3], C[4], 8, 3, 1, 0, 0),
        ("conv5", C[4], C[5], 8, 3, 1, 1, 0),
        ("fc6", C[5], cfg["F6"], 4, 4, 0, 0, 0),
        ("fc7", cfg["F6"], cfg["F7"], 1, 1, 0, 0, 0),
        ("fc8", cfg["F7"], cfg["NCLS"], 1, 1, 0, 0, 1),
    ]
    out, wbase, tbase = [], 0, 0
    for name, cin, cout, H, K, pad, pool, raw in spec:
        Hc = H + 2 * pad - K + 1
        Ho = Hc // 2 if pool else Hc
        L = dict(name=name, cin=cin, cout=cout, H=H, K=K, pad=pad, pool=pool, raw=raw, Hc=Hc, Ho=Ho,
                 cig=-(-cin // PI), nt=-(-cout // PO), lgW=int(np.log2(H)), lgWo=int(np.log2(Ho)),
                 wbase=wbase, tbase=tbase)
        assert 2 ** L["lgW"] == H and 2 ** L["lgWo"] == Ho
        L["cigkk"] = L["cig"] * K * K
        L["steps"] = L["nt"] * Hc * Hc * L["cigkk"]
        wbase += L["nt"] * L["cigkk"]
        tbase += L["nt"]
        out.append(L)
    return out


def check_bank_capacity(layers, depth=256):
    for L in layers[1:]:                 # layer 0 reads the image buffer
        need = ((L["cig"] - 1) >> 2) * L["H"] * L["H"] + L["H"] * L["H"]
        assert need <= depth, f"{L['name']}: activation bank needs {need} words"
    for L in layers:
        if not L["raw"]:
            assert L["nt"] * L["Ho"] * L["Ho"] <= depth


def weight_words(Q, layers):
    rows = []
    for q, L in zip(Q, layers):
        K = L["K"]
        if L["name"].startswith("conv"):
            w = q["wq"]
        else:
            w = q["wq"].reshape(L["cout"], L["cin"], K, K)      # fc6: (c, y, x) flatten order
        wp = np.zeros((L["nt"] * PO, L["cig"] * PI, K, K), np.int64)
        wp[:L["cout"], :L["cin"]] = w
        # word (t, n=(cg*K+ky)*K+kx), lane o, input i
        v = wp.reshape(L["nt"], PO, L["cig"], PI, K, K).transpose(0, 2, 4, 5, 1, 3)
        rows.append(v.reshape(-1, PO, PI))
    rom = np.concatenate(rows) & 0xFF
    words = np.zeros(rom.shape[:2], np.uint64)
    for i in range(PI):
        words |= rom[:, :, i].astype(np.uint64) << np.uint64(8 * i)
    return words


def tile_params(Q, layers):
    nt = sum(L["nt"] for L in layers)
    B = np.zeros((nt, PO), np.int64)
    M = np.zeros((nt, PO), np.int64)
    S = np.ones((nt, PO), np.int64)
    for q, L in zip(Q, layers):
        sl = slice(L["tbase"], L["tbase"] + L["nt"])
        for arr, src in ((B, q["bq"]), (M, q["M"]), (S, q["sh"])):
            v = np.zeros(L["nt"] * PO, np.int64)
            v[:L["cout"]] = src
            if arr is S:
                v[L["cout"]:] = 1
            arr[sl] = v.reshape(L["nt"], PO)
        if not L["raw"]:
            m, s = M[sl], S[sl]
            y = np.minimum((ACC_CLAMP * m + (1 << (s - 1))) >> s, 255)
            assert ((y == 255) | (m == 0)).all(), f"{L['name']}: 24-bit clamp would not be exact"
        assert q["worst_acc"] < 2 ** 31
    return B, M, S


def write_header(path, layers, words, B, M, S):
    L8 = layers
    with open(path, "w") as f:
        f.write("// generated by model/export_hls.py -- DO NOT EDIT\n")
        f.write("// AlexNet-C10 int8 weights (CIFAR-10, QAT), stored as on-chip ROMs.\n")
        f.write("#ifndef CIFAR_WEIGHTS_H\n#define CIFAR_WEIGHTS_H\n#include <ap_int.h>\n\n")
        f.write(f"#define NW_WORDS {words.shape[0]}\n#define NTILES {B.shape[0]}\n\n")
        f.write("// {K, pad, pool, raw, lgW, lgWo, Hc, cig, nt, wbase, tbase}\n")
        f.write("static const LayerCfg LCFG[NLAYERS] = {\n")
        for L in L8:
            f.write(f"    {{{L['K']}, {L['pad']}, {L['pool']}, {L['raw']}, {L['lgW']}, {L['lgWo']}, "
                    f"{L['Hc']}, {L['cig']}, {L['nt']}, {L['wbase']}, {L['tbase']}}},  // {L['name']}\n")
        f.write("};\n\n")
        f.write("// weight ROM: word [n][o] = 8 int8 weights (input channel cg*8+i in bits 8i+7:8i)\n")
        f.write("static const ap_uint<64> WROM[NW_WORDS][PO] = {\n")
        for r in words:
            f.write("{" + ",".join(f"0x{int(v):016x}ULL" for v in r) + "},\n")
        f.write("};\n\n")
        for name, arr, ty in (("BIAS", B, "ap_int<32>"), ("MULT", M, "ap_uint<16>"), ("SHIFT", S, "ap_uint<6>")):
            f.write(f"static const {ty} {name}[NTILES][PO] = {{\n")
            for r in arr:
                f.write("{" + ",".join(str(int(v)) for v in r) + "},\n")
            f.write("};\n\n")
        f.write("#endif\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qat", default=os.path.join(HERE, "trained", "qat.pt"))
    ap.add_argument("--data", default=os.path.join(ROOT, "build", "data", "cifar10_uint8.npz"))
    ap.add_argument("--n-golden", type=int, default=100)
    a = ap.parse_args()
    import torch
    from net import CFG
    d = torch.load(a.qat, weights_only=False)
    folded = [(n, w.numpy(), b.numpy()) for n, w, b in zip(d["names"], d["w"], d["b"])]
    Q = qm.quantize(folded, d["act_scales"], qm.build_layers(CFG))
    layers = hls_layers(CFG)
    check_bank_capacity(layers)

    data = np.load(a.data)
    xte, yte = data["x_test"], data["y_test"].astype(np.int64)
    logits = qm.forward_int(xte, Q, qm.build_layers(CFG))
    pred = qm.argmax_first(logits)
    acc = float((pred == yte).mean())
    print(f"exact integer model (= HLS kernel), CIFAR-10 test 10,000 images: top-1 = {acc*100:.2f}%")

    words = weight_words(Q, layers)
    B, M, S = tile_params(Q, layers)
    write_header(os.path.join(ROOT, "hls", "include", "cifar_weights.h"), layers, words, B, M, S)
    steps = sum(L["steps"] for L in layers)
    for L in layers:
        print(f"  {L['name']:5s} K={L['K']} H={L['H']:2d} pool={L['pool']} cig={L['cig']:3d} tiles={L['nt']} "
              f"steps={L['steps']}")
    print(f"weight ROM {words.shape[0]} x {PO} x 64 bit; MAC steps per image {steps}")

    gd = os.path.join(ROOT, "hls", "testbench", "data")
    os.makedirs(gd, exist_ok=True)
    n = min(a.n_golden, len(xte))
    with open(os.path.join(gd, "images.txt"), "w") as f:
        for i in range(n):
            f.write(" ".join(f"{w:x}" for w in qm.image_words(xte[i])) + "\n")
    with open(os.path.join(gd, "expected.txt"), "w") as f:
        for i in range(n):
            f.write(" ".join(str(int(v)) for v in logits[i]) + f" {int(pred[i])} {int(yte[i])}\n")

    dep = os.path.join(ROOT, "build", "deploy")
    os.makedirs(dep, exist_ok=True)
    np.savez_compressed(os.path.join(dep, "cifar10_test.npz"), x=xte, y=yte.astype(np.uint8),
                        expected_logits=logits.astype(np.int32))
    np.savez_compressed(os.path.join(dep, "int_params.npz"),
                        **{f"{q['name']}_{k}": q[k] for q in Q for k in ("wq", "bq", "M", "sh")})
    json.dump(dict(classes=CLASSES, int_test_acc=acc, mac_steps=int(steps),
                   fc8_logit_scale=float(Q[-1]["s_in"] * Q[-1]["s_w"][0])),
              open(os.path.join(dep, "model_info.json"), "w"), indent=1)
    print("wrote hls/include/cifar_weights.h, hls/testbench/data/, build/deploy/")


if __name__ == "__main__":
    main()
